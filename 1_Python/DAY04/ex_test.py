## [문제2] 1~100범위에서 3의 배수와 7의 배수 숫자만 저장하세요.
##        그리고 해당 데이터에서 가장 큰수, 가장 작은 수 출력하세요.
##        그리고 해당 데이터를 내림차순으로 정렬해 주세요.
## =================================================
## 3의 배수 : 3, 6, 9, .....
## 7의 배수 : 7, 14, 21, 28, ....
threeNums = list( range(3, 101, 3) )
sevenNums = list( range(7, 101, 7) )
nums = threeNums + sevenNums 

## -> 3의 배수와 7의 배수 숫자만 저장
nums = list( range(3, 101, 3) ) + list( range(7, 101, 7) )

## -> 최대값, 최소값 : 내장함수 max(), min()
print(f"데이터 : {nums}\n최대값 : {max(nums)}\t최소값 : {min(nums)}")

## -> 정렬 : 내장함수 sorted(),  list 메서드 sort() 
print(f"내림차순 정렬 - 내장 함수  : {sorted(nums, reverse=True)} \n=> {nums}")
print(f"내림차순 정렬 - list메서드 : {nums.sort(reverse=True)} \n=> {nums}")

