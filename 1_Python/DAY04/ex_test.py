## 저장 후 변경 불가 ==> tuple 저장해야함!! Read Only
personInfo1 = ("001224-4234567", "여", "홍길동")
personInfo2 = "001224-4234567", "여", "홍길동"

## -> 데이터 타입 확인
print(f"타입 : {type(personInfo1)},  {type(personInfo2)}")

## -> 원소 변경 시도 : 튜플 변경 불가 !!! 
personInfo1[2] = "홍이장군"

## -> 튜플 => 리스트 형변환/캐스팅
personInfo1 = list( personInfo1 ) 
personInfo1[2] = "홍이장군"

## -> 리스트 => 튜플 형변환/캐스팅
print(f"타입 : {type(personInfo1)},  {personInfo1}")